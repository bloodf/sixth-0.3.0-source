// Builds src/data/icons.gen.ts from open icon sets. Run: node tools/icons.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
const gi = JSON.parse(readFileSync('node_modules/@iconify-json/game-icons/icons.json')).icons,
  lu = JSON.parse(readFileSync('node_modules/@iconify-json/lucide/icons.json')).icons;
export const CREST =
  'wolf-head direwolf lion tiger-head fox-head bear-head raven eagle-head eagle-emblem barn-owl cobra hydra dragon-head sea-dragon shark-jaws bull stag-head horse-head feline cat spiked-dragon-head phoenix-head griffin-symbol samurai-helmet spartan-helmet viking-helmet black-knight-helm crown queen-crown skull-crossed-bones crossed-swords crossed-axes trident thor-hammer power-lightning lightning-helix flame sun moon-claws star-formation anchor big-wave mountaintop crystal-growth rose lotus-flower thorny-vine eye-target all-seeing-eye radar-sweep processor hourglass feathered-wing angel-wings scorpion spider-alt octopus whale-tail dragonfly bat-mask ghost robot-golem hand-of-god helmet-head-shot winged-sword laurel-crown'
    .split(' ')
    .filter(k => gi[k] || (console.log('no', k), 0));
const src = [];
const walk = d => {
  for (const f of readdirSync(d)) {
    const p = d + '/' + f;
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.tsx?$/.test(f) && !/gen\.ts/.test(f)) src.push(readFileSync(p, 'utf8'));
  }
};
walk('src');
const all = src.join('\n');
const want = new Set(CREST);
for (const m of all.matchAll(/['"]([a-z0-9]+(?:-[a-z0-9]+)*)['"]/g)) if (gi[m[1]] && m[1].length > 2) want.add(m[1]);
const lw = new Set();
for (const m of all.matchAll(/\b(?:I|i|icon|ic)=["']([a-z0-9-]+)["']/g)) if (lu[m[1]]) lw.add(m[1]);
for (const m of all.matchAll(/icon: '([a-z0-9-]+)'/g)) if (lu[m[1]]) lw.add(m[1]);
for (const m of all.matchAll(/\bUI\('([a-z0-9-]+)'/g)) if (lu[m[1]]) lw.add(m[1]);
const p = b => b.replace(/fill="currentColor"\s?/g, '');
const path = b => [...b.matchAll(/ d="([^"]+)"/g)].map(m => m[1]).join('');
let out =
  '// Generated by tools/icons.mjs. Game-icons.net (CC BY 3.0) and Lucide (ISC).\nexport const CREST_ICONS = ' +
  JSON.stringify(CREST) +
  ';\n/** 512x512 filled paths */\nexport const GI: Record<string, string> = {\n';
for (const k of [...want].sort()) out += `  ${JSON.stringify(k)}: ${JSON.stringify(path(gi[k].body))},\n`;
out += '};\n/** 24x24 stroked markup */\nexport const LU: Record<string, string> = {\n';
for (const k of [...lw].sort()) out += `  ${JSON.stringify(k)}: ${JSON.stringify(p(lu[k].body))},\n`;
out += '};\n';
writeFileSync('src/data/icons.gen.ts', out);
console.log(want.size, 'game icons', lw.size, 'ui icons', ((out.length / 1024) | 0) + 'KB');
