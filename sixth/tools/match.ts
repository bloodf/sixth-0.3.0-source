import '@fontsource-variable/anybody';
import '@fontsource-variable/sofia-sans';
import { Engine } from '../src/gfx/engine.ts';
import { MatchView } from '../src/gfx/match.ts';
import { mockCfg } from '../src/sim/mock.ts';
import { loadHumans } from '../src/gfx/human.ts';
await loadHumans();
const q = new URLSearchParams(location.search);
const e = new Engine(document.getElementById('c') as any, (q.get('q') as any) ?? undefined);
e.resize(innerWidth, innerHeight);
e.auto = false;
const t = (q.get('t') ?? 'cs2') as any;
const m = q.get('m') ?? { cs2: 'kasbah', val: 'halcyon', dota: 'oldvale', ow: 'solstice' }[t as 'cs2'];
await document.fonts.ready;
const t0 = performance.now();
const v = new MatchView(e, mockCfg(t, m, q.get('s') ?? 'a'), document.getElementById('o')!);
console.log('build', performance.now() - t0);
const skip = +(q.get('skip') ?? 0);
for (let i = 0; i < skip; i++) (v as any).tickOnce();
v.mode = (q.get('cam') ?? 'action') as any;
v.speed = +(q.get('sp') ?? 1);
e.setView(v);
(window as any).fps = () => e.fps + ' ' + e.q + ' calls ' + e.r.info.render.calls + ' tris ' + e.r.info.render.triangles;
(window as any).v = v;
(window as any).e = e;
