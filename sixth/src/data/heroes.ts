import type { TitleId } from './titles.ts';
export function heroPool(t: TitleId, role: string): { id: string; name: string; icon: string; sub: string }[] {
  if (t === 'dota') return MOBA.filter(h => h.pos.includes(role)).map(h => ({ id: h.id, name: h.name, icon: h.icon, sub: h.title }));
  if (t === 'ow') return OW.filter(h => h.role === OW_ROLE[role]).map(h => ({ id: h.id, name: h.name, icon: h.icon, sub: h.ult.name }));
  if (t === 'val')
    return AGENTS.filter(h => VAL_ROLE[role].includes(h.role)).map(h => ({ id: h.id, name: h.name, icon: h.icon, sub: h.sig }));
  return [];
}
