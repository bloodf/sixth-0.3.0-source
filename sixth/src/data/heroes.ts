/** Original heroes and agents. Bodies are assembled procedurally from `body` + colours. */
export type Body =
  'soldier' | 'operator' | 'brute' | 'knight' | 'mage' | 'rogue' | 'archer' | 'priest' | 'beast' | 'mech' | 'light' | 'robe';
export interface Look {
  body: Body;
  c1: string;
  c2: string;
  glow: string;
  head: 'bare' | 'hood' | 'horns' | 'helm' | 'crown' | 'mask' | 'visor' | 'antlers' | 'mohawk' | 'hat';
  prop: 'sword' | 'axe' | 'staff' | 'bow' | 'hammer' | 'orb' | 'spear' | 'daggers' | 'rifle' | 'cannon' | 'shield' | 'pistols' | 'none';
  cape?: boolean;
  s?: number;
}
const L = (body: Body, c1: string, c2: string, glow: string, head: Look['head'], prop: Look['prop'], cape = false, s = 1): Look => ({
  body,
  c1,
  c2,
  glow,
  head,
  prop,
  cape,
  s,
});

export type MobaKind = 'nuke' | 'aoe' | 'stun' | 'heal' | 'dash' | 'shield' | 'slow';
export interface MobaAbility {
  k: MobaKind;
  name: string;
  cd: number;
  mana: number;
  range: number;
  pow: number;
  r?: number;
}
export interface MobaHero {
  id: string;
  name: string;
  title: string;
  icon: string;
  pos: string[];
  hp: number;
  dmg: number;
  as: number;
  range: number;
  speed: number;
  mana: number;
  arm: number;
  ab: MobaAbility[];
  ult: MobaAbility;
  look: Look;
}
const a = (k: MobaKind, name: string, cd: number, mana: number, range: number, pow: number, r?: number): MobaAbility => ({
  k,
  name,
  cd,
  mana,
  range,
  pow,
  r,
});
